//
// 기존에는 accuracy/wpm 버킷마다 문장이 딱 하나씩 고정돼 있어서, 버킷이 같은 두 학생은
// 토씨 하나 다르지 않은 리포트를 받았다. 여기서는 버킷 구조(accuracy/speed/balanced)는
// 그대로 두고, 버킷마다 여러 변형을 두어 resultId 기반으로 결정적으로 하나를 골라 쓴다.
// (매번 새로고침해도 같은 리포트는 같은 문구가 나와야 하므로 무작위가 아니라 시드 기반 선택)
//
// ⚠️ 아동 대상 유료 콘텐츠 문구 — 여기 배열에 항목을 추가/수정할 때는 반드시 직접 검수 후 반영할 것.

export type CopyBucket = "accuracy" | "speed" | "balanced";

export function getCopyBucket(accuracy: number, wpm: number): CopyBucket {
  if (accuracy < 90) return "accuracy";
  if (wpm < 85) return "speed";
  return "balanced";
}

/**
 * seed(리포트 고유 id 등)와 fieldKey(문구 종류)를 조합한 문자열을 해싱해서
 * variants 배열 중 하나를 결정적으로 골라준다. 같은 seed+fieldKey는 항상 같은 결과.
 */
export function pickVariant<T>(seed: string, fieldKey: string, variants: T[]): T {
  const str = `${seed}:${fieldKey}`;
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    hash = (hash * 31 + str.charCodeAt(i)) >>> 0;
  }
  return variants[hash % variants.length];
}

